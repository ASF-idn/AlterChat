class SettingsDialog(ctk.CTkToplevel):
    """Language, theme, AI model path and the 'Clear All Data' action."""

    def __init__(self, master: Any, *, settings: dict[str, Any], fonts: dict[str, ctk.CTkFont],
                 model_status: str, on_language: Callable[[str], None],
                 on_theme: Callable[[str], None], on_model_selected: Callable[[str], str],
                 on_clear_all: Callable[[tk.Misc], None]) -> None:
        super().__init__(master)
        self._settings = dict(settings)
        self._fonts = fonts
        self._on_language = on_language
        self._on_theme = on_theme
        self._on_model_selected = on_model_selected
        self._on_clear_all = on_clear_all

        self.title(tr("settings_title"))
        self.resizable(False, False)
        self.configure(fg_color=Palette.SIDEBAR_BG)
        self.protocol("WM_DELETE_WINDOW", self.close)
        self._build(model_status)
        center_window(self, 520, 600, master)
        make_modal(self, master)

    def _build(self, model_status: str) -> None:
        pad = {"padx": 26}
        ctk.CTkLabel(self, text=tr("settings_title"), font=self._fonts["title"],
                     text_color=Palette.TEXT).pack(anchor="w", pady=(22, 6), **pad)

        # Language -----------------------------------------------------------
        self._section(tr("language"))
        lang_labels = list(LANGUAGE_LABELS.values())
        self._lang_button = ctk.CTkSegmentedButton(
            self, values=lang_labels, command=self._language_changed,
            selected_color=Palette.ACCENT, selected_hover_color=Palette.ACCENT_HOVER)
        self._lang_button.set(LANGUAGE_LABELS.get(self._settings.get("language", "en"), "English"))
        self._lang_button.pack(fill="x", **pad)

        # Theme --------------------------------------------------------------
        self._section(tr("theme"))
        self._theme_map = {tr("theme_system"): "System", tr("theme_dark"): "Dark",
                           tr("theme_light"): "Light"}
        self._theme_button = ctk.CTkSegmentedButton(
            self, values=list(self._theme_map), command=self._theme_changed,
            selected_color=Palette.ACCENT, selected_hover_color=Palette.ACCENT_HOVER)
        current_theme = self._settings.get("theme", "System")
        self._theme_button.set(next(k for k, v in self._theme_map.items() if v == current_theme))
        self._theme_button.pack(fill="x", **pad)

        # Model --------------------------------------------------------------
        self._section(tr("ai_model"))
        model_row = ctk.CTkFrame(self, fg_color="transparent")
        model_row.pack(fill="x", **pad)
        model_row.grid_columnconfigure(0, weight=1)
        current = self._settings.get("model_path") or ""
        self._model_label = ctk.CTkLabel(model_row, text=ellipsize(Path(current).name if current else
                                                                    tr("model_none"), 40),
                                         font=self._fonts["small"], text_color=Palette.TEXT, anchor="w")
        self._model_label.grid(row=0, column=0, sticky="ew")
        ctk.CTkButton(model_row, text=tr("browse"), width=100, command=self._browse_model).grid(
            row=0, column=1, padx=(8, 0))
        self._model_status = ctk.CTkLabel(self, text=model_status, font=self._fonts["small"],
                                          text_color=Palette.TEXT_MUTED, anchor="w", justify="left",
                                          wraplength=460)
        self._model_status.pack(fill="x", pady=(4, 0), **pad)

        # Danger zone --------------------------------------------------------
        self._section(tr("danger_zone"), color=Palette.DANGER)
        ctk.CTkLabel(self, text=tr("clear_all_desc"), font=self._fonts["small"],
                     text_color=Palette.TEXT_MUTED, anchor="w").pack(fill="x", **pad)
        ctk.CTkButton(self, text=tr("clear_all"), fg_color=Palette.DANGER, hover_color=Palette.DANGER_HOVER,
                      height=36, command=lambda: self._on_clear_all(self)).pack(anchor="w", pady=(8, 0), **pad)

        # Footer -------------------------------------------------------------
        footer = ctk.CTkFrame(self, fg_color="transparent")
        footer.pack(side="bottom", fill="x", pady=20, **pad)
        ctk.CTkLabel(footer, text=tr("about", version=dm.APP_VERSION), font=self._fonts["tiny"],
                     text_color=Palette.TEXT_MUTED, anchor="w").pack(side="left")
        ctk.CTkButton(footer, text=tr("close"), width=100, fg_color=Palette.ACCENT,
                      hover_color=Palette.ACCENT_HOVER, command=self.close).pack(side="right")

    def _section(self, title: str, color: Any = Palette.TEXT) -> None:
        ctk.CTkLabel(self, text=title, font=self._fonts["item_name"], text_color=color,
                     anchor="w").pack(fill="x", padx=26, pady=(18, 6))

    # ------------------------------------------------------------ handlers
    def _language_changed(self, label: str) -> None:
        code = next((c for c, lbl in LANGUAGE_LABELS.items() if lbl == label), "en")
        if code == self._settings.get("language"):
            return
        self.close()            # the app rebuilds the UI and reopens Settings
        self._on_language(code)

    def _theme_changed(self, label: str) -> None:
        mode = self._theme_map.get(label, "System")
        self._settings["theme"] = mode
        self._on_theme(mode)

    def _browse_model(self) -> None:
        path = filedialog.askopenfilename(
            parent=self, title=tr("ai_model"),
            filetypes=[(tr("gguf_filetype"), "*.gguf"), (tr("all_files"), "*.*")])
        if not path:
            return
        self._model_label.configure(text=ellipsize(Path(path).name, 40))
        self._model_status.configure(text=self._on_model_selected(path))

    def set_model_status(self, text: str) -> None:
        if widget_alive(self):
            self._model_status.configure(text=text)

    def close(self) -> None:
        try:
            self.grab_release()
        except tk.TclError:
            pass
        self.destroy()


