def _initials(name: str) -> str:
    words = [w for w in re.split(r"\s+", (name or "").strip()) if w]
    letters = [next((ch for ch in w if ch.isalnum()), "") for w in words[:2]]
    return "".join(letters).upper() or "?"


def _load_font(size_px: int) -> ImageFont.ImageFont:
    """Best available bold TrueType font, falling back to Pillow's default."""
    for candidate in ("segoeuib.ttf", "seguisb.ttf", "arialbd.ttf", "Arial Bold.ttf",
                      "DejaVuSans-Bold.ttf", "LiberationSans-Bold.ttf"):
        try:
            return ImageFont.truetype(candidate, size_px)
        except OSError:
            continue
    try:
        return ImageFont.load_default(size=size_px)
    except TypeError:  # Pillow < 10.1
        return ImageFont.load_default()


