    def _label(self, text: str) -> None:
        ctk.CTkLabel(self, text=text, font=self._fonts["item_name"], text_color=Palette.TEXT,
                     anchor="w").pack(fill="x", padx=26, pady=(16, 4))

    # ------------------------------------------------------------ avatar
    def _choose_avatar(self) -> None:
        path = filedialog.askopenfilename(
            parent=self, title=tr("choose_photo"),
            filetypes=[(tr("images_filetype"), "*.png *.jpg *.jpeg *.webp *.bmp *.gif"),
                       (tr("all_files"), "*.*")])
        if not path:
            return
        try:
            with Image.open(path) as img:
                img.verify()  # cheap integrity check
        except Exception:
            self._show_error(tr("err_image"))
            return
        self._avatar_path = path
        self._remove_photo_btn.configure(state="normal")
        self._refresh_avatar_preview()

    def _remove_avatar(self) -> None:
        self._avatar_path = None
        self._remove_photo_btn.configure(state="disabled")
        self._refresh_avatar_preview()

    def _refresh_avatar_preview(self) -> None:
        name = self._name_entry.get().strip() or "?"
        path = Path(self._avatar_path) if self._avatar_path else None
        self._avatar_preview.configure(image=get_avatar_image(path, name, 76))

    # ---------------------------------------------------------- WA export
    def _choose_file(self) -> None:
        path = filedialog.askopenfilename(
            parent=self, title=tr("choose_file"),
            filetypes=[(tr("chat_filetype"), "*.txt *.zip"), (tr("all_files"), "*.*")])
        if not path:
            return
        self._wa_path = path
        self._parsed = None
        self._file_label.configure(text=ellipsize(Path(path).name, 34))
        self._set_busy(True, tr("parsing"))

        def worker() -> None:
            try:
                parsed = dm.parse_whatsapp_export(path)
                self._dispatcher.call(self._on_parsed, path, parsed, None)
            except Exception as exc:  # noqa: BLE001 - shown to the user
                logger.exception("Parsing failed")
                self._dispatcher.call(self._on_parsed, path, None, str(exc))

        threading.Thread(target=worker, name="alterchat-parser", daemon=True).start()

    def _on_parsed(self, path: str, parsed: Optional[dm.ParsedChat], error: Optional[str]) -> None:
        if not widget_alive(self) or path != self._wa_path:
            return  # dialog closed or another file chosen meanwhile
        self._set_busy(False)
        if error:
            self._show_error(tr("err_parse", error=error))
            return
        if parsed is None or not parsed.messages:
            self._show_error(tr("err_no_messages"))
            self._reset_sender_menu()
            return

        self._parsed = parsed
        self._parse_info.configure(text=tr("parsed_info", messages=len(parsed.messages),
                                            senders=len(parsed.sender_counts)))
        self._sender_map = {f"{s}  ({parsed.sender_counts[s]})": s for s in parsed.senders}
        self._sender_menu.configure(values=list(self._sender_map), state="normal")
        self._sender_manual = False
        self._auto_select_sender()

    def _reset_sender_menu(self) -> None:
        self._sender_map = {}
        self._sender_menu.configure(values=[tr("sender_none")], state="disabled")
        self._sender_menu.set(tr("sender_none"))
        self._sender_hint.configure(text="")
        self._parse_info.configure(text="")

    def _auto_select_sender(self) -> None:
        """Preselect the sender that matches the typed contact name."""
        if self._parsed is None or self._sender_manual:
            return
        match = dm.match_sender(self._name_entry.get(), self._parsed.senders)
        if match is None:
            self._sender_menu.set(tr("sender_choose"))
            self._sender_hint.configure(text="")
            return
        label = next(lbl for lbl, sender in self._sender_map.items() if sender == match)
        self._sender_menu.set(label)
        self._sender_hint.configure(text=tr("sender_auto"))

    def _on_sender_chosen(self, _value: str) -> None:
        self._sender_manual = True
        self._sender_hint.configure(text="")
        self._show_error("")

    def _on_name_changed(self, _event: Any = None) -> None:
        if not self._avatar_path:
            self._refresh_avatar_preview()
        self._auto_select_sender()

    # -------------------------------------------------------------- save
    def _save(self) -> None:
        if self._busy:
            return
        name = self._name_entry.get().strip()
        if not name:
            self._show_error(tr("err_name"))
            return
        if self._parsed is None:
            self._show_error(tr("err_file"))
            return
        friend_sender = self._sender_map.get(self._sender_menu.get())
        if not friend_sender:
            self._show_error(tr("err_sender"))
            return
        count = self._parsed.sender_counts.get(friend_sender, 0)
        if count < dm.MIN_FRIEND_MESSAGES:
            self._show_error(tr("err_few_messages", count=count, name=friend_sender,
                                min=dm.MIN_FRIEND_MESSAGES))
            return

        self._set_busy(True, tr("saving"))
        parsed, avatar = self._parsed, self._avatar_path

        def worker() -> None:
            try:
                contact = self._data.create_contact(name, friend_sender, parsed, avatar)
                self._dispatcher.call(self._on_save_done, contact, None)
            except Exception as exc:  # noqa: BLE001
                logger.exception("Saving contact failed")
                self._dispatcher.call(self._on_save_done, None, str(exc))

        threading.Thread(target=worker, name="alterchat-persona", daemon=True).start()

    def _on_save_done(self, contact: Optional[dict[str, Any]], error: Optional[str]) -> None:
        if contact is not None:
            # Notify the app even if the dialog was closed in the meantime.
            self._on_saved(contact)
            if widget_alive(self):
                self._close()
            return
        if widget_alive(self):
            self._set_busy(False)
            self._show_error(tr("err_save", error=error))

    # ----------------------------------------------------------- helpers
    def _set_busy(self, busy: bool, message: str = "") -> None:
        self._busy = busy
        state = "disabled" if busy else "normal"
        self._save_button.configure(state=state)
        self._file_button.configure(state=state)
        self._status.configure(text=message, text_color=Palette.TEXT_MUTED)

    def _show_error(self, message: str) -> None:
        self._status.configure(text=message, text_color=Palette.DANGER)

    def _cancel(self) -> None:
        self._close()

    def _close(self) -> None:
        try:
            self.grab_release()
        except tk.TclError:
            pass
        self.destroy()


