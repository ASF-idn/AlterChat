def tr(key: str, **kwargs: Any) -> str:
    """Translate ``key`` for the active language (falls back to English/key)."""
    text = I18N.get(_current_language, {}).get(key) or I18N["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


