class UIDispatcher:
    """Run callables on the Tk main thread.

    Tkinter is not thread-safe: worker threads must never touch widgets.
    Workers call :meth:`call`, which only puts work into a ``queue.Queue``;
    the main loop drains that queue every few milliseconds via ``after``.
    """

    def __init__(self, root: tk.Misc, interval_ms: int = 30) -> None:
        self._root = root
        self._interval = interval_ms
        self._queue: "queue.Queue[tuple[Callable[..., Any], tuple, dict]]" = queue.Queue()
        self._running = True
        self._root.after(self._interval, self._drain)

    def call(self, func: Callable[..., Any], *args: Any, **kwargs: Any) -> None:
        """Schedule ``func(*args, **kwargs)`` on the main thread (any thread)."""
        if self._running:
            self._queue.put((func, args, kwargs))

    def _drain(self) -> None:
        processed = 0
        while processed < 200:  # bound work per tick to keep the UI responsive
            try:
                func, args, kwargs = self._queue.get_nowait()
            except queue.Empty:
                break
            try:
                func(*args, **kwargs)
            except Exception:
                logger.exception("Dispatched UI callback failed")
            processed += 1
        if self._running:
            try:
                self._root.after(self._interval, self._drain)
            except tk.TclError:
                self._running = False

    def stop(self) -> None:
        self._running = False


