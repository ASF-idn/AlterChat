def widget_alive(widget: Optional[tk.Misc]) -> bool:
    """``True`` if the Tk widget still exists (safe on destroyed widgets)."""
    if widget is None:
        return False
    try:
        return bool(widget.winfo_exists())
    except tk.TclError:
        return False


def center_window(win: tk.Misc, width: int, height: int, parent: Optional[tk.Misc] = None) -> None:
    """Centre ``win`` on ``parent`` (if visible) or on the screen.

    CustomTkinter scales width/height by the DPI factor but not x/y, so the
    offsets are computed with the scaled size.
    """
    try:
        scale = ctk.ScalingTracker.get_window_scaling(win)
    except Exception:
        scale = 1.0
    real_w, real_h = int(width * scale), int(height * scale)
    win.update_idletasks()
    if parent is not None and widget_alive(parent) and parent.winfo_viewable():
        x = parent.winfo_rootx() + (parent.winfo_width() - real_w) // 2
        y = parent.winfo_rooty() + (parent.winfo_height() - real_h) // 2
    else:
        x = (win.winfo_screenwidth() - real_w) // 2
        y = (win.winfo_screenheight() - real_h) // 3
    win.geometry(f"{width}x{height}+{max(x, 0)}+{max(y, 0)}")


def make_modal(win: tk.Toplevel, parent: Optional[tk.Misc]) -> None:
    """Make a ``CTkToplevel`` modal (transient + grab) once it is visible."""
    if parent is not None:
        try:
            win.transient(parent)
        except tk.TclError:
            pass

    def _activate() -> None:
        if not widget_alive(win):
            return
        try:
            win.lift()
            win.focus_force()
            win.grab_set()
        except tk.TclError:
            pass  # window not viewable yet / already destroyed

    win.after(150, _activate)


def ellipsize(text: str, limit: int) -> str:
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "\u2026"


def format_clock(timestamp: Optional[datetime]) -> str:
    return timestamp.strftime("%H:%M") if timestamp else ""


def format_list_time(iso_value: Optional[str]) -> str:
    """Sidebar time label: HH:MM today, 'Yesterday', otherwise dd/mm/yy."""
    if not iso_value:
        return ""
    try:
        value = datetime.fromisoformat(iso_value)
    except ValueError:
        return ""
    today = date.today()
    if value.date() == today:
        return value.strftime("%H:%M")
    if value.date() == today - timedelta(days=1):
        return tr("yesterday")
    return value.strftime("%d/%m/%y")


def format_date_separator(day: date) -> str:
    today = date.today()
    if day == today:
        return tr("today")
    if day == today - timedelta(days=1):
        return tr("yesterday")
    return day.strftime("%d/%m/%Y")


