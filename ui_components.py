        self._fonts = fonts
        self._resolve_avatar = resolve_avatar
        self._on_send = on_send
        self._on_clear_chat = on_clear_chat
        self._on_delete_contact = on_delete_contact

        self._contact: Optional[dict[str, Any]] = None
        self._bubbles: list[MessageBubble] = []
        self._reply_bubble: Optional[MessageBubble] = None
        self._last_date: Optional[date] = None
        self._wraplength = 420
        self._resize_job: Optional[str] = None
        self._scroll_job: Optional[str] = None
        self._send_enabled = True

