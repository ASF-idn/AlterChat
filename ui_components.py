    # -------------------------------------------------------------- layout
    def _build_empty_view(self) -> ctk.CTkFrame:
        frame = ctk.CTkFrame(self, fg_color=Palette.HEADER_BG, corner_radius=0)
        inner = ctk.CTkFrame(frame, fg_color="transparent")
